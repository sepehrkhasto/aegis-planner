"""Generate v1 test vectors and sample vault files from the 2.x reference code in legacy/.

    python tools/vectors/gen_v1.py vectors     # deterministic known-answer vectors -> testdata/v1/vectors.json
    python tools/vectors/gen_v1.py samples     # random sample vaults -> testdata/v1/samples/ (run once, then commit)
    python tools/vectors/gen_v1.py check       # vectors.json is up to date and every sample still opens in 2.x

Known-answer vectors use fixed inputs, so `vectors` always produces the same file; CI runs `check`.
Sample vaults contain random salts and nonces exactly like real files, so they are generated once and committed.
"""
from __future__ import annotations

import base64
import copy
import hashlib
import json
import sys
import tempfile
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "legacy"))

from cryptography.hazmat.primitives.ciphers.aead import AESGCM  # noqa: E402

from aegis_desktop.core import crypto, logic, store  # noqa: E402

OUT = ROOT / "testdata" / "v1"
SAMPLES = OUT / "samples"
FAST = 100_000          # the lowest count 2.x accepts: keeps the test suite quick


def hx(b: bytes) -> str:
    return b.hex()


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode("ascii")


def seq(n: int, start: int = 0) -> bytes:
    return bytes((start + i) & 0xFF for i in range(n))


# ---------------------------------------------------------------- vectors ---
def pbkdf2_vectors() -> list[dict]:
    cases = [(b"password", b"salt", 1), (b"password", b"salt", 2), (b"password", b"salt", 4096),
             ("رمز عبور ۱۲۳".encode(), seq(16), 1000), (b"", seq(16, 7), 1),
             ("یک رمز با ي عربی".encode(), seq(16, 99), FAST), (b"correct horse battery", seq(16, 200), 600_000)]
    return [{"secret": hx(s), "salt": hx(salt), "iterations": n, "key": hx(crypto._derive(s, salt, n))}
            for s, salt, n in cases]


def aead_vectors() -> list[dict]:
    out = []
    for i, pt in enumerate([b"", b"a", seq(15), seq(16), seq(17), seq(32), "سلام دنیا 🌍".encode(), seq(1000, 3)]):
        key, nonce = seq(32, 10 * i), seq(12, 50 + i)
        out.append({"key": hx(key), "nonce": hx(nonce), "plaintext": hx(pt),
                    "ciphertext": hx(AESGCM(key).encrypt(nonce, pt, None))})
    return out


PASSWORDS = ["hunter2-hunter2", "رمز‌اصلی", "رمز ي و ك", "يك كليد", "ىمالي",
             "café", "café", "ی ک ي ك ى", "é ي", "", "🔐 قفل"]


def variant_vectors() -> list[dict]:
    return [{"input": p, "variants": crypto.password_variants(p)} for p in PASSWORDS]


def base32_vectors() -> dict:
    enc = [{"bytes": hx(b), "text": crypto._to_base32(b)} for b in
           [b"", b"\x00", b"\xff", seq(5), seq(19), seq(20), seq(21, 77), bytes(20), b"\xff" * 20]]
    texts = ["AEGIS-0A1B2-C3D4E-F5G6H-J7K8M-N9PQR-STVWX-YZ", "aegis-0a1b2-c3d4e", "OIL-U-oilu", "  12 34\t56 ",
             "Straße ſ ﬁ", "ٱ۱۲۳ AB", "AEGIS--", "", "zzzzzzzz"]
    dec = [{"text": t, "bytes": hx(crypto._from_base32(t))} for t in texts]
    cand = [{"text": t, "candidates": crypto._recovery_candidates(t)} for t in
            ["AEGIS-ABCDE-12345", "  aegis-abcde ", "ABCDE-12345", "a-e-g-i-s-x", "", "  x  "]]
    return {"encode": enc, "decode": dec, "candidates": cand}


def wrap_vectors() -> list[dict]:
    out = []
    for i, (pw, n) in enumerate([("hunter2-hunter2", FAST), ("رمز ي و ك", FAST), ("پسورد خیلی خوب", 600_000)]):
        salt, nonce, dek = seq(16, i), seq(12, 30 + i), seq(32, 60 + i)
        kek = crypto._derive(pw.encode(), salt, n)
        out.append({"password": pw, "salt": hx(salt), "iterations": n, "kek": hx(kek), "nonce": hx(nonce),
                    "dek": hx(dek), "wrapped": hx(AESGCM(kek).encrypt(nonce, dek, None))})
    return out


def build_vectors() -> dict:
    return {"comment": "Generated by tools/vectors/gen_v1.py from legacy/ (Aegis 2.x). Do not edit by hand.",
            "unicodedata": unicodedata.unidata_version, "pbkdf2_sha256": pbkdf2_vectors(),
            "aes256gcm": aead_vectors(), "password_variants": variant_vectors(), "base32": base32_vectors(),
            "key_wrap": wrap_vectors()}


def dump(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


# ---------------------------------------------------------------- samples ---
def _seed() -> dict:
    v: dict = {}
    logic.starter_content(v)
    v["tasks"].append(logic.new_task("جلسه با استاد 🎓", tags=["دانشگاه", "مهم"], pr="high",
                                     subs=[{"text": "اسلایدها", "done": True}, {"text": "سؤال‌ها", "done": False}]))
    return v


def _make_store(tmp: Path, name: str) -> store.VaultStore:
    s = store.VaultStore(tmp / name)
    s.unlock_backup_s = 0
    return s


def _write(name: str, raw: dict, case: dict) -> dict:
    path = SAMPLES / f"sample-{name}.json"
    path.write_text(json.dumps(raw, ensure_ascii=False), encoding="utf-8")
    return {"file": path.name, **case}


def _plain(raw: dict, dek: bytes) -> dict:
    if not raw["ciphertext"]:
        return {"plaintext_sha256": None}
    pt = AESGCM(dek).decrypt(base64.b64decode(raw["ciphertextIv"]), base64.b64decode(raw["ciphertext"]), None)
    return {"plaintext_sha256": hashlib.sha256(pt).hexdigest(), "plaintext_len": len(pt)}


def build_samples() -> dict:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    for old in SAMPLES.glob("sample-*.json"):
        old.unlink()
    cases = []
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        # 1. a real 2.x vault (600k iterations), saved by VaultStore
        s = _make_store(tmp, "a")
        s.create("hunter2-hunter2", seed=_seed())
        raw = json.loads(s.path.read_text(encoding="utf-8"))
        cases.append(_write("standard", raw, {"password": "hunter2-hunter2", "expect": "ok",
                                              "dek": hx(bytes(s._dek)), **_plain(raw, bytes(s._dek))}))
        good = raw
        # 2. recovery key on the same vault
        key = s.setup_recovery()
        raw = json.loads(s.path.read_text(encoding="utf-8"))
        cases.append(_write("recovery", raw, {"password": "hunter2-hunter2", "recovery_key": key,
                                              "recovery_key_typed": key.lower().replace("aegis-", "  "),
                                              "expect": "ok", "dek": hx(bytes(s._dek)), **_plain(raw, bytes(s._dek))}))
        # 3. password created with Arabic yeh/kaf, typed later on a Persian keyboard
        s = _make_store(tmp, "b")
        s.create("كليد ي ۱۴۰۵", seed=_seed())
        raw = json.loads(s.path.read_text(encoding="utf-8"))
        cases.append(_write("arabic-keyboard", raw, {"password": "کلید ی ۱۴۰۵", "expect": "ok",
                                                     "dek": hx(bytes(s._dek)), **_plain(raw, bytes(s._dek))}))
    # 4. fast vault with no data yet (empty ciphertext), the shape create() writes before its first save
    meta, dek = crypto.create_key_material("empty-vault-pw", iterations=FAST)
    raw = {"format": "securevault1", **meta.to_dict(), "ciphertext": "", "ciphertextIv": "", "recovery": None,
           "revision": 0, "unknownFutureField": {"keep": True}}
    cases.append(_write("empty", raw, {"password": "empty-vault-pw", "expect": "ok", "dek": hx(dek),
                                       "plaintext_sha256": None}))
    # 5. negative cases derived from the standard vault
    def bad(name: str, mutate, expect: str, password: str = "hunter2-hunter2"):
        r = copy.deepcopy(good)
        mutate(r)
        cases.append(_write(name, r, {"password": password, "expect": expect}))

    def flip(field):
        def f(r):
            b = bytearray(base64.b64decode(r[field]))
            b[len(b) // 2] ^= 0x01
            r[field] = b64(bytes(b))
        return f
    bad("wrong-password", lambda r: None, "wrong_password", password="hunter2-hunter3")
    bad("tampered-ciphertext", flip("ciphertext"), "damaged")
    bad("tampered-wrapped-key", flip("wrappedKey"), "wrong_password")
    bad("iterations-too-low", lambda r: r.update(iterations=99_999), "invalid")
    bad("iterations-too-high", lambda r: r.update(iterations=5_000_001), "invalid")
    bad("iterations-bool", lambda r: r.update(iterations=True), "invalid")
    bad("iterations-float", lambda r: r.update(iterations=600000.0), "invalid")
    bad("unknown-kdf", lambda r: r.update(kdf="scrypt"), "invalid")
    bad("missing-salt", lambda r: r.pop("salt"), "invalid")
    bad("salt-not-string", lambda r: r.update(salt=123), "invalid")
    return {"comment": "Sample vaults written by legacy/ (Aegis 2.x). expect: ok | wrong_password | damaged | invalid.",
            "cases": cases}


# ------------------------------------------------------------------ check ---
def legacy_outcome(path: Path, password: str) -> str:
    """What 2.x itself does when the file is its live vault: the oracle for every sample's `expect`.
    damaged = the password unwrapped the key but the data failed authentication; invalid = refused before that."""
    with tempfile.TemporaryDirectory() as td:
        s = _make_store(Path(td), "v")
        s.dir.mkdir(parents=True)
        s.path.write_bytes(path.read_bytes())
        try:
            s.unlock(password)
            return "ok"
        except crypto.WrongPassword:
            return "wrong_password"
        except store.VaultError as e:
            return "damaged" if str(e).startswith("رمز درست است") else "invalid"


def check() -> int:
    errors = 0
    if (OUT / "vectors.json").read_text(encoding="utf-8") != dump(build_vectors()):
        print("vectors.json is out of date: run `gen_v1.py vectors`")
        errors += 1
    index = json.loads((SAMPLES / "index.json").read_text(encoding="utf-8"))
    for c in index["cases"]:
        got = legacy_outcome(SAMPLES / c["file"], c["password"])
        if got != c["expect"]:
            print(f"{c['file']}: 2.x says {got}, index says {c['expect']}")
            errors += 1
        for k in ("recovery_key", "recovery_key_typed"):
            if k in c:
                raw = json.loads((SAMPLES / c["file"]).read_text(encoding="utf-8"))
                if crypto.unwrap_with_recovery(c[k], raw["recovery"]).hex() != c["dek"]:
                    print(f"{c['file']}: {k} does not open the vault in 2.x")
                    errors += 1
    print("ok" if not errors else f"{errors} problem(s)")
    return 1 if errors else 0


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "vectors":
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / "vectors.json").write_text(dump(build_vectors()), encoding="utf-8")
        return 0
    if cmd == "samples":
        idx = build_samples()
        (SAMPLES / "index.json").write_text(dump(idx), encoding="utf-8")
        return check()
    if cmd == "check":
        return check()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
